"""校验 advance 缩放系数：字符在图集中按 64px 格绘制，但屏幕上目标宽度 =
   汉字 32px（fChsWidth），故缩放 = advance/64 * (64/2) = advance/2 用于屏幕宽度系数。"""

# 字体渲染时，汉字在 64px 格内以 size=58 渲染，其 advance = 58
# 屏幕目标：汉字占 32px（fChsWidth），即 58 -> 32 的映射
# 所以「单位 advance（0..64）-> 屏幕宽」的比例应为 32/64 = 0.5

print("汉字 advance = 58 -> 屏幕宽 = 58 * 0.5 = 29.0  (期望贴近 32)")
print("字母 'A' advance = 41 -> 屏幕宽 = 20.5     (原版 ~ 41/96*? 需对照)")

# 原版拉丁字符在 64px 格内的宽度：游戏原版字体表 fUnpropValue / iPropValues
# 原版 4096 图集里拉丁格是 64 宽，汉字补丁把汉字压进 32 -> 0.5
# 因此拉丁字母用同一系数 0.5 也是自洽的（图集里拉丁与汉字同格）

# 结论：advance 直接 /2 换算成屏幕像素宽，与 fChsWidth=32 的体系一致。
for ch, adv in [("A", 41), ("i", 15), ("W", 59), ("国", 58), ("，", 58)]:
    print("  %-2s adv=%d -> %.1f px" % (ch, adv, adv / 2.0))
